export const workoutFocusGroups = [
  'Chest',
  'Back',
  'Biceps',
  'Triceps',
  'Shoulders',
  'Legs',
  'Cardio',
  'Core',
] as const;

export type WorkoutFocusGroup = (typeof workoutFocusGroups)[number];

export const getExerciseNameKey = (name: string) => {
  return name.trim().toLowerCase();
};

export const getFocusGroupForMuscle = (muscleName: string): WorkoutFocusGroup | null => {
  const muscle = muscleName.toLowerCase();
  if (muscle.includes('cardio')) return 'Cardio';
  if (muscle.includes('chest')) return 'Chest';
  if (/back|lats|traps/.test(muscle)) return 'Back';
  if (muscle.includes('biceps')) return 'Biceps';
  if (muscle.includes('triceps')) return 'Triceps';
  if (/shoulder|deltoid/.test(muscle)) return 'Shoulders';
  if (/quadriceps|hamstrings|glutes|calves|legs/.test(muscle)) return 'Legs';
  if (/core|abs|obliques/.test(muscle)) return 'Core';
  return null;
};

export const getExerciseFocusGroup = (exercise: Exercise): WorkoutFocusGroup | null => {
  for (const muscle of [exercise.muscle, ...exercise.secondaryMuscles]) {
    const focus = getFocusGroupForMuscle(muscle);
    if (focus) return focus;
  }
  return exercise.category === 'Arms' ? null : exercise.category;
};

export const exerciseMatchesFocus = (exercise: Exercise, focusGroups: ReadonlySet<string>) => {
  if (focusGroups.size === 0) return true;
  if (focusGroups.has(exercise.category)) return true;

  return [exercise.muscle, ...exercise.secondaryMuscles]
    .some((muscle) => {
      const focus = getFocusGroupForMuscle(muscle);
      return focus !== null && focusGroups.has(focus);
    });
};

export const exerciseMatchesPrimaryFocus = (exercise: Exercise, focusGroups: ReadonlySet<string>) => {
  if (focusGroups.size === 0) return true;

  const primaryFocus = getFocusGroupForMuscle(exercise.muscle)
    ?? (exercise.category === 'Cardio' ? 'Cardio' : null);
  return primaryFocus !== null && focusGroups.has(primaryFocus);
};

